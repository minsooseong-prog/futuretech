/* ── 트랙 보간 ── */
function sampleTrack(keys, t) {
  if (t <= keys[0][0]) return keys[0][1];
  const last = keys[keys.length - 1];
  if (t >= last[0]) return last[1];
  for (let i = 0; i < keys.length - 1; i++) {
    const a = keys[i], b = keys[i + 1];
    if (t >= a[0] && t <= b[0]) {
      const span = b[0] - a[0];
      if (span <= 1e-6) return b[1];
      const u = (t - a[0]) / span;
      const s = u * u * (3 - 2 * u); // smoothstep — 관절이 부드럽게 가감속
      return a[1] + (b[1] - a[1]) * s;
    }
  }
  return last[1];
}

/** 클립을 t(0~1)에서 샘플링 → {joint: deg} */
export function sampleClip(clip, t) {
  const out = {};
  for (const [joint, keys] of Object.entries(clip.tracks)) out[joint] = sampleTrack(keys, t);
  return out;
}
